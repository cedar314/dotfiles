#!/usr/bin/env python3
"""Persist an XDG choice without executing or printing existing shell contents."""
import argparse
import fcntl
import hashlib
import json
import os
from pathlib import Path
import shlex
import sys
import tempfile

from files import exists, private_state, safe_parents, save

MARKER = '# dotfiles-bootstrap-v1 '


def status(kind, message):
    print(f'[{kind}] {message}', file=sys.stderr)


def metadata(path):
    # Read only a recognized generated header, never source an arbitrary file.
    if path.is_symlink() or not path.is_file():
        return None
    try:
        with path.open() as stream:
            header = stream.readline(16384)
    except UnicodeError:
        return None
    if not header.startswith(MARKER):
        return None
    try:
        value = json.loads(header[len(MARKER):])
        if (not isinstance(value, dict) or set(value) != {'config_home', 'repo', 'previous'}
                or not isinstance(value['config_home'], str) or not isinstance(value['repo'], str)
                or (value['previous'] is not None and not isinstance(value['previous'], str))):
            return None
        return value
    except ValueError:
        return None


def render(value):
    lines = [MARKER + json.dumps(value, sort_keys=True),
             '# Generated by dotfiles setup; path selection is local to this machine.']
    if value['previous']:
        previous = shlex.quote(value['previous'])
        lines.append(f'if [ -r {previous} ]; then . {previous}; fi')
    lines.extend([
        'export XDG_CONFIG_HOME=' + shlex.quote(value['config_home']),
        '. ' + shlex.quote(str(Path(value['repo']) / 'zsh/.zshenv')),
        '',
    ])
    return '\n'.join(lines)


def choose(args, saved):
    selected = os.environ.get('XDG_CONFIG_HOME') or (saved or {}).get('config_home')
    if not selected:
        selected = str(Path(args.home) / '.config')
        if args.mode == 'apply':
            print(f'XDG_CONFIG_HOME [{selected}] (Enter for default): ', end='', file=sys.stderr, flush=True)
            response = sys.stdin.readline()
            if not response:
                raise ValueError('No path response; provide XDG_CONFIG_HOME or answer the prompt')
            selected = response.strip() or selected
        else:
            status('planned', f'XDG_CONFIG_HOME is unset; using {selected} for this read-only preview')
    # Expand only the familiar home prefix, never evaluate shell expressions.
    if selected == '~' or selected.startswith('~/'):
        selected = str(Path(args.home)) + selected[1:]
    if not selected.startswith('/') or any(ord(c) < 32 or ord(c) == 127 for c in selected):
        raise ValueError('XDG_CONFIG_HOME must be an absolute path without control characters')
    selected = os.path.normpath(selected)
    repo = Path(args.repo).resolve()
    if Path(selected) == repo or repo in Path(selected).parents:
        raise ValueError('XDG_CONFIG_HOME must be outside the repository')
    safe_parents(Path(selected) / 'placeholder')
    return selected


def bootstrap(args):
    destination = Path(args.home) / '.zshenv'
    saved = metadata(destination)
    selected = choose(args, saved)
    previous = saved.get('previous') if saved else None
    value = {'config_home': selected, 'repo': str(Path(args.repo).resolve()), 'previous': previous}
    content = render(value)
    if saved == value and destination.read_text() == content:
        status('already configured', '~/.zshenv persists the selected XDG configuration path')
        print(selected)
        return 0
    if args.mode != 'apply':
        status('missing', f'Would configure {destination} to persist XDG_CONFIG_HOME={selected}')
        print(selected)
        return 2 if args.mode == 'check' else 0
    safe_parents(destination)
    snapshot = destination.lstat() if exists(destination) else None
    if snapshot:
        print(f'Existing {destination}: back up and install the environment wrapper, or skip? [b/S] ',
              end='', file=sys.stderr, flush=True)
        if sys.stdin.readline().strip().lower() not in ('b', 'backup'):
            raise ValueError('Environment setup skipped; module setup stopped without changing the existing .zshenv')
    root = Path(args.state).absolute()
    private_state(root, Path(args.repo).resolve())
    with (root / 'lock').open('a') as lock:
        fcntl.flock(lock, fcntl.LOCK_EX)
        if (destination.lstat() if exists(destination) else None) != snapshot:
            raise ValueError('.zshenv changed while waiting; left untouched')
        run = Path(tempfile.mkdtemp(prefix='link-', dir=root))
        backup = run / 'original'
        # Known repository links only contain shared defaults, already sourced below.
        managed_link = destination.is_symlink() and destination.resolve() == Path(args.repo).resolve() / 'zsh/.zshenv'
        generated_unchanged = saved is not None and destination.read_text() == render(saved)
        if snapshot and not managed_link and not generated_unchanged:
            value['previous'] = str(backup)
        content = render(value)
        record = {'kind': 'file', 'destination': str(destination), 'source': None,
                  'backup': str(backup) if snapshot else None, 'status': 'prepared',
                  'sha256': hashlib.sha256(content.encode()).hexdigest()}
        manifest = run / 'manifest.json'
        save(manifest, record)
        if snapshot:
            destination.rename(backup)
        created = False
        try:
            with open(destination, 'x', opener=lambda path, flags: os.open(path, flags, 0o600)) as stream:
                created = True
                stream.write(content)
        except BaseException:
            if created:
                destination.unlink()
            if snapshot and not exists(destination):
                backup.rename(destination)
            record['status'] = 'failed'
            save(manifest, record)
            raise
        record['status'] = 'linked'
        save(manifest, record)
    status('configured', f'{destination}; recovery: {manifest}')
    print(selected)
    return 0


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('--home', required=True)
    parser.add_argument('--repo', required=True)
    parser.add_argument('--state', required=True)
    parser.add_argument('--mode', choices=['apply', 'check', 'dry-run'], required=True)
    args = parser.parse_args()
    try:
        return bootstrap(args)
    except (OSError, ValueError, KeyError) as error:
        status('failed', str(error))
        return 1


if __name__ == '__main__':
    sys.exit(main())
